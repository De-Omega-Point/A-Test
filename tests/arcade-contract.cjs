/* Dependency-free regression tests: node tests/arcade-contract.cjs */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
const storage = new Map(), nodes = new Map();
const node = () => ({ innerHTML: '', textContent: '', style: {}, dataset: {}, classList: { add() {}, remove() {}, toggle() {} }, querySelector() { return null; }, querySelectorAll() { return []; }, addEventListener() {}, setAttribute() {}, removeAttribute() {}, focus() {} });
const main = node();
const document = { querySelector: s => s === '#app' ? main : null, querySelectorAll: () => [], addEventListener() {}, body: node(), getElementById(id) { if (!nodes.has(id)) nodes.set(id, node()); return nodes.get(id); } };
const context = vm.createContext({ console, document, window: { addEventListener() {}, scrollTo() {} }, navigator: {}, location: { hash: '' }, history: { pushState() {} }, matchMedia: () => ({ matches: false }), localStorage: { getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, String(v)) }, AbortController, queueMicrotask: () => {}, setInterval: () => 1, clearInterval() {}, requestAnimationFrame: () => 1, cancelAnimationFrame() {} });
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
let arcade = fs.readFileSync(path.join(root, 'arcade.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
check(html.includes('arcade.css?v=thumb-v6') && html.includes('arcade.js?v=thumb-v6'), 'Entry point loads both versioned arcade assets');
check(!html.includes('\\n'), 'No visible escaped newlines in HTML');
check(!arcade.includes('document.body.dataset.view'), 'Body metadata cannot hijack delegated navigation');
check(arcade.includes("cancelAnimationFrame(this.frame)"), 'Animation has an explicit cleanup path');
check(arcade.includes("this.resize.disconnect()"), 'Resize observer is disconnected on exit');
vm.runInContext(app, context);
arcade = arcade.replace("  route(location.hash.slice(1) || 'home', true);", "  globalThis.testAPI = { worlds, DashRun, chooseQuestions, hash, rng, creditAnswer, data };\n  route(location.hash.slice(1) || 'home', true);");
vm.runInContext(arcade, context);
const { worlds, DashRun, chooseQuestions, hash, rng, creditAnswer, data } = context.testAPI;
check(worlds.length === 4, 'Four curriculum worlds');
for (let w = 0; w < 4; w++) {
  const deck = chooseQuestions(w, 'adventure', 123);
  check(deck.length === 3, `World ${w} has three checkpoints`);
  check(new Set(deck.map(i => i.q[1])).size === 3, `World ${w} has distinct prompts`);
  check(deck.every(i => i.q[0] === worlds[w].part), `World ${w} questions match its curriculum part`);
  check(deck.every(i => i.options.filter(o => o.original === i.q[3]).length === 1), `World ${w} preserves the answer key when shuffling`);
}
const daily = chooseQuestions(0, 'daily', hash('2026-10-03'));
check(daily.length === 4 && new Set(daily.map(i => i.q[0])).size === 4, 'Daily includes all four parts');
check(JSON.stringify(daily) === JSON.stringify(chooseQuestions(0, 'daily', hash('2026-10-03'))), 'Daily questions and choices are reproducible');
check(JSON.stringify(daily) !== JSON.stringify(chooseQuestions(0, 'daily', hash('2026-10-04'))), 'A new local date changes the course');
const randomA = rng(23), randomB = rng(23);
check(Array.from({length: 20}, () => randomA()).every(n => n >= 0 && n < 1), 'Seeded randomness stays in range');
check(randomB() === rng(23)(), 'Seeded obstacle path is deterministic');
const question = daily[0].q;
creditAnswer(question, false);
const firstState = vm.runInContext('JSON.stringify(state)', context);
creditAnswer(question, true);
check(vm.runInContext('JSON.stringify(state)', context) === firstState, 'Replaying a question cannot inflate practice evidence');
check(data.credited.filter(q => q === question[1]).length === 1, 'Question credit is deduplicated');
let r = new DashRun(0, 'adventure', 123); r.phase = 'running'; r.hud = () => {}; r.message = () => {};
r.objects = [{ lane: 1, y: .82, kind: 'star' }]; r.update(0);
check(r.stars === 1 && r.score === 10, 'Stars are collected by lane collision');
r.objects = [{ lane: 0, y: .82, kind: 'star' }]; r.update(0);
check(r.stars === 1, 'Stars in other lanes are not collected');
r.objects = [{ lane: 1, y: .82, kind: 'bumper' }]; r.update(0);
check(r.shields === 2 && r.streak === 0, 'Bumpers cost one shield and reset combo');
r.objects = [{ lane: 1, y: .82, kind: 'bumper' }]; r.update(0);
check(r.shields === 2, 'Grace period prevents double damage');
r.invulnerable = 0; r.shields = 1; let failed = false; r.finish = success => { failed = !success; r.phase = 'result'; }; r.objects = [{ lane: 1, y: .82, kind: 'bumper' }]; r.update(0);
check(failed, 'Zero shields ends the run');
r = new DashRun(0, 'adventure', 456); r.phase = 'running'; r.hud = () => {}; for (let i = 0; i < 12; i++) r.collect(.82);
check(r.score > 120 && r.stars === 12 && r.maxStreak === 12, 'Star combos reward uninterrupted collection');
let opened = false; r.openCheckpoint = () => { opened = true; r.phase = 'question'; }; r.elapsed = 9.99; r.update(.02);
check(opened, 'Action stops at the checkpoint boundary');
r = new DashRun(0, 'adventure', 789); r.phase = 'question'; r.show = () => {}; r.hud = () => {}; r.shields = 2;
const correct = r.deck[0].options.findIndex(o => o.original === r.deck[0].q[3]); r.answer(correct);
check(r.correct === 1 && r.score === 120 && r.shields === 3 && r.phase === 'feedback', 'Correct answer awards points, restores shield and locks feedback');
r.answer(correct);
check(r.correct === 1 && r.score === 120, 'Double taps cannot score twice');
r = new DashRun(1, 'chill', 987); r.phase = 'running'; r.show = () => {}; r.correct = 3; const oldRuns = data.runs; r.finish(true); r.finish(true);
check(data.runs === oldRuns + 1, 'Run rewards are saved only once');
check(data.cleared.includes(1) && data.medals[1] === 3, 'A completed world and medal persist');
vm.runInContext("session = { mode: 'mock' }; mockTimer = 123; route('home');", context);
check(vm.runInContext('mockTimer === null && session === null', context), 'Navigating away clears the mock timer and session');
console.log(`${checks} arcade contract checks passed.`);
